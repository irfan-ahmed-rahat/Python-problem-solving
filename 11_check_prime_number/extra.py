import math

num = int(input("Enter number: "))
is_prime = True

if num > 1:
    # আমরা শুধু সংখ্যাটির বর্গমূল পর্যন্ত চেক করব
    limit = math.isqrt(num) + 1 
    
    for i in range(2, limit):
        if num % i == 0:
            is_prime = False
            break
else:
    is_prime = False

if is_prime:
    print("prime")
else:
    print("not prime")



