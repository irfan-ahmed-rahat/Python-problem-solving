unit = float(input("Enter your unit: "))

if unit <= 100:
    # প্রথম ১০০ ইউনিটের জন্য (প্রতি ইউনিট ৫ টাকা)
    bill = unit * 5

elif unit <= 200:
    # প্রথম ১০০ ইউনিট (ফিক্সড ৫০০ টাকা) + বাকি ইউনিটের জন্য (১০ টাকা রেট)
    bill = (100 * 5) + ((unit - 100) * 10)

else:
    # প্রথম ১০০ ইউনিট (৫ টাকা রেট) + দ্বিতীয় ১০০ ইউনিট (১০ টাকা রেট) + বাকি ইউনিটের জন্য (২০ টাকা রেট)
    bill = (100 * 5) + (100 * 10) + ((unit - 200) * 20)

print(f"Your total bill is: {bill} TK")
